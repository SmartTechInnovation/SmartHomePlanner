# same English word, different Romanian depending on where it is used: (context, source)
RO_CTX = {
    ("Renderer", "Group"): "Grup",
    ("PropertiesPanel", "Group"): "Grup",
    ("PdfExporter", "Group"): "Grup",
    ("MainWindow", "Group"): "Grupare",
}

def main(path):
    tree = ET.parse(path)
    missing = []
    ctx_of = {}
    for c in tree.iter("context"):
        name = c.find("name").text
        for m in c.iter("message"):
            ctx_of[id(m)] = name
    for m in tree.iter("message"):
        src = m.find("source").text
        if (ctx_of.get(id(m)), src) in RO_CTX and m.get("numerus") != "yes":
            tr = m.find("translation")
            tr.text = RO_CTX[(ctx_of.get(id(m)), src)]
            tr.attrib.pop("type", None)
            continue
        tr = m.find("translation")
        if m.get("numerus") == "yes":
            forms = PLURAL.get(src)
            if not forms:
                missing.append(src); continue
            for f in list(tr):
                tr.remove(f)
            for f in forms:
                ET.SubElement(tr, "numerusform").text = f
        else:
            t = RO.get(src)
            if t is None:
                missing.append(src); continue
            tr.text = t
        tr.attrib.pop("type", None)
    tree.write(path, encoding="utf-8", xml_declaration=True)
    if missing:
        print("MISSING:", missing)

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "translations/SmartHomePlanner_ro.ts")
